-- Backup: dados completos preservados antes de apagar.
CREATE TABLE IF NOT EXISTS backup_medidores_2025_excluidos AS
SELECT m.*, NOW() AS excluido_em
FROM   medidores_list m
JOIN   _alvo_exclusao a ON a.id = m.id;

CREATE TABLE IF NOT EXISTS backup_medidor_logs_2025_excluidos AS
SELECT l.*, NOW() AS excluido_em
FROM   medidor_logs l
JOIN   _alvo_exclusao a ON a.id = l.medidor_id;

-- medidor_logs não tem ON DELETE CASCADE de verdade (checado no catálogo),
-- então precisa apagar manualmente pra não deixar log órfão.
DELETE FROM medidor_logs l
USING  _alvo_exclusao a
WHERE  l.medidor_id = a.id;

DELETE FROM medidores_list m
USING  _alvo_exclusao a
WHERE  m.id = a.id;

